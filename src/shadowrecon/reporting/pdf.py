def generate_pdf_html(
    store: SessionStore,
    meta: Optional[Dict[str, Any]] = None,
    diff: Optional[SessionDiff] = None,
) -> str:
    """Render full styled HTML markup suitable for WeasyPrint PDF conversion."""
    target = store.get_metadata("target", meta.get("Target", "unknown") if meta else "unknown")
    domain = store.get_metadata("domain", meta.get("Domain", "unknown") if meta else "unknown")
    start_time = store.get_metadata("start_time", datetime.now().isoformat())
    counts = store.get_summary_counts()
    findings = store.get_findings()
    stages = store.get_stages()

    by_sev: Dict[str, int] = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
    for f in findings:
        s = f.severity.lower()
        by_sev[s] = by_sev.get(s, 0) + 1

    sub_count = counts.get("Subdomains", len(store.get_subdomains()))
    host_count = counts.get("Live hosts", len(store.get_hosts()))
    url_count = counts.get("Parameterized URLs", len(store.get_urls()))

    sev_order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}
    sorted_findings = sorted(
        findings,
        key=lambda f: (sev_order.get(f.severity.lower(), 5), f.vuln_type, f.target_url),
    )

    h_target = html.escape(str(target))
    h_domain = html.escape(str(domain))
    h_date = html.escape(str(start_time))

    content: List[str] = [
        "<!DOCTYPE html>",
        "<html>",
        "<head>",
        "<meta charset='utf-8'>",
        f"<title>ShadowRecon Report - {h_domain}</title>",
        f"<style>{PDF_STYLESHEET}</style>",
        "</head>",
        "<body>",
        f"<h1>Security Assessment Report</h1>",
        f"<div class='subtitle'>Target: {h_domain} &bull; Generated: {h_date} &bull; ShadowRecon v{__version__}</div>",
        "<h2>Executive Summary</h2>",
        "<div class='meta-grid'>",
        f"<div class='meta-row'><div class='meta-label'>Target URL</div><div class='meta-value'>{h_target}</div></div>",
        f"<div class='meta-row'><div class='meta-label'>Domain</div><div class='meta-value'>{h_domain}</div></div>",
        f"<div class='meta-row'><div class='meta-label'>Assessment Date</div><div class='meta-value'>{h_date}</div></div>",
        f"<div class='meta-row'><div class='meta-label'>Total Subdomains</div><div class='meta-value'>{sub_count}</div></div>",
        f"<div class='meta-row'><div class='meta-label'>Live HTTP/S Hosts</div><div class='meta-value'>{host_count}</div></div>",
        f"<div class='meta-row'><div class='meta-label'>Parameterized URLs</div><div class='meta-value'>{url_count}</div></div>",
        "</div>",
        "<div class='summary-cards'>",
        f"<div class='summary-card critical'><span class='summary-num' style='color:#dc2626'>{by_sev.get('critical', 0)}</span><span class='summary-label'>Critical</span></div>",
        f"<div class='summary-card high'><span class='summary-num' style='color:#ea580c'>{by_sev.get('high', 0)}</span><span class='summary-label'>High</span></div>",
        f"<div class='summary-card medium'><span class='summary-num' style='color:#d97706'>{by_sev.get('medium', 0)}</span><span class='summary-label'>Medium</span></div>",
        f"<div class='summary-card low'><span class='summary-num' style='color:#2563eb'>{by_sev.get('low', 0)}</span><span class='summary-label'>Low</span></div>",
        f"<div class='summary-card info'><span class='summary-num' style='color:#64748b'>{by_sev.get('info', 0)}</span><span class='summary-label'>Info</span></div>",
        "</div>",
    ]

    # Findings Table
    content.append("<h2>Identified Vulnerabilities</h2>")
    if not sorted_findings:
        content.append("<p style='color: #64748b; font-style: italic;'>No vulnerabilities were identified during this assessment session.</p>")
    else:
        content.append("<table>")
        content.append("<thead><tr><th style='width:12%'>Severity</th><th style='width:28%'>Vulnerability</th><th style='width:15%'>CWE</th><th style='width:33%'>Target</th><th style='width:12%'>Tool</th></tr></thead>")
        content.append("<tbody>")
        for f in sorted_findings:
            sev = f.severity.lower()
            badge_class = f"badge badge-{sev}"
            cwe_id, _, _, _ = resolve_cwe_metadata(f.vuln_type)
            content.append("<tr>")
            content.append(f"<td><span class='{badge_class}'>{html.escape(sev.upper())}</span></td>")
            content.append(f"<td><strong>{html.escape(f.vuln_type)}</strong></td>")
            content.append(f"<td>{html.escape(cwe_id or '-')}</td>")
            content.append(f"<td>{html.escape(f.target_url or '-')}</td>")
            content.append(f"<td><code>{html.escape(f.source_tool)}</code></td>")
            content.append("</tr>")
        content.append("</tbody></table>")

    # High / Critical Findings Details Section
    high_crit = [f for f in sorted_findings if f.severity.lower() in ("critical", "high")]
    if high_crit:
        content.append("<h2>High & Critical Vulnerability Analysis</h2>")
        for f in high_crit:
            cwe_id, cwe_name, cvss, _ = resolve_cwe_metadata(f.vuln_type)
            sev = f.severity.lower()
            content.append("<div class='finding-card'>")
            content.append(f"<div style='margin-bottom: 4pt;'><span class='badge badge-{sev}'>{sev.upper()}</span> <strong style='font-size:10pt;'>{html.escape(f.vuln_type)}</strong></div>")
            content.append(f"<div style='font-size:8.5pt; color:#475569; margin-bottom:4pt;'><strong>Target:</strong> {html.escape(f.target_url)} &bull; <strong>Tool:</strong> {html.escape(f.source_tool)} &bull; <strong>CWE:</strong> {html.escape(cwe_id)} ({html.escape(cwe_name)}) &bull; <strong>CVSS:</strong> {cvss}</div>")
            if f.payload:
                content.append(f"<div style='font-size:8pt;'><strong>Match / Payload:</strong> <code>{html.escape(f.payload)}</code></div>")
            if f.details:
                content.append(f"<div class='code-box'>{html.escape(f.details[:400])}</div>")
            content.append("</div>")

    # Cross-Session Differential Drift (if present)
    if diff:
        status_changes = getattr(diff, "status_changes", [])
        content.append("<h2>Cross-Session Differential Drift</h2>")
        content.append("<div class='meta-grid'>")
        content.append(f"<div class='meta-row'><div class='meta-label'>New Vulnerabilities</div><div class='meta-value'><strong>{len(diff.new_findings)}</strong></div></div>")
        content.append(f"<div class='meta-row'><div class='meta-label'>Resolved Vulnerabilities</div><div class='meta-value'><strong>{len(diff.resolved_findings)}</strong></div></div>")
        content.append(f"<div class='meta-row'><div class='meta-label'>New Subdomains</div><div class='meta-value'>{len(diff.new_subdomains)}</div></div>")
        content.append(f"<div class='meta-row'><div class='meta-label'>Status Code Shifts (e.g. 403 &rarr; 200)</div><div class='meta-value'>{len(status_changes)}</div></div>")
        content.append("</div>")

    # Pipeline Stages Summary
    if stages:
        stage_list: List[Dict[str, Any]] = []
        if isinstance(stages, dict):
            for st_name, st_info in stages.items():
                item = dict(st_info) if isinstance(st_info, dict) else {}
                item["stage_name"] = st_name
                stage_list.append(item)
        elif isinstance(stages, list):
            stage_list = stages

        if stage_list:
            content.append("<h2>Pipeline Execution Performance</h2>")
            content.append("<table>")
            content.append("<thead><tr><th>Stage</th><th>Status</th><th>Duration</th><th>Error / Notes</th></tr></thead>")
            content.append("<tbody>")
            for s in stage_list:
                content.append("<tr>")
                content.append(f"<td><code>{html.escape(s.get('stage_name', ''))}</code></td>")
                content.append(f"<td>{html.escape(s.get('status', ''))}</td>")
                content.append(f"<td>{s.get('duration_seconds', 0.0):.2f}s</td>")
                content.append(f"<td>{html.escape(s.get('error_message', '') or '-')}</td>")
                content.append("</tr>")
            content.append("</tbody></table>")

    content.append("</body></html>")
    return "\n".join(content)


def export_pdf(
    store: SessionStore,
    output_path: Path,
    meta: Optional[Dict[str, Any]] = None,
    diff: Optional[SessionDiff] = None,
) -> Path:
    """Generate executive PDF report using WeasyPrint and write to output_path."""
    if not _WEASYPRINT_AVAILABLE or weasyprint is None:
        raise RuntimeError(
            f"WeasyPrint or its system C dependencies (libpango, libcairo) are not available: {_WEASYPRINT_ERROR}. "
            "Please install system libraries ('sudo apt install python3-weasyprint' or 'sudo apt install libpango-1.0-0 libcairo2')."
        )
    html_markup = generate_pdf_html(store, meta=meta, diff=diff)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    weasyprint.HTML(string=html_markup).write_pdf(target=str(output_path))
    log.info("Executive PDF report generated -> %s (%d bytes)", output_path, output_path.stat().st_size)
    return output_path
